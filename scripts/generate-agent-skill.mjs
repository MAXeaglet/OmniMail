// Generate MCP resources/prompts from omnimail-skill Markdown files.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { join, relative, basename } from 'node:path'

const root = process.cwd()
const skillDir = join(root, 'omnimail-skill')
const outFile = join(root, 'email-worker/src/features/agent/agent-skill-data.ts')

function files(dir) {
  const out = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (existsSync(full) && full.endsWith('.md')) out.push(full)
  }
  return out
}

function slug(path) {
  return relative(skillDir, path)
    .replaceAll('\\', '/')
    .replace(/\.md$/, '')
}

const resources = []
const prompts = []

if (existsSync(skillDir)) {
  for (const file of files(skillDir)) {
    resources.push({
      uri: `omnimail://${slug(file)}`,
      name: basename(file, '.md'),
      description: `OmniMail skill guide: ${basename(file, '.md')}`,
      text: readFileSync(file, 'utf8'),
    })
  }
  if (existsSync(join(skillDir, 'guides'))) {
    for (const file of files(join(skillDir, 'guides'))) {
      resources.push({
        uri: `omnimail://guides/${basename(file, '.md')}`,
        name: basename(file, '.md'),
        description: `OmniMail guide: ${basename(file, '.md')}`,
        text: readFileSync(file, 'utf8'),
      })
    }
  }
  if (existsSync(join(skillDir, 'workflows'))) {
    for (const file of files(join(skillDir, 'workflows'))) {
      prompts.push({
        name: basename(file, '.md').replaceAll('_', ' '),
        description: `OmniMail workflow: ${basename(file, '.md')}`,
        messages: [{
          role: 'user',
          content: { type: 'text', text: readFileSync(file, 'utf8') },
        }],
      })
    }
  }
}

const content = [
  '// AUTO-GENERATED by scripts/generate-agent-skill.mjs. Do not edit.',
  'export const AGENT_SKILL_RESOURCES = ' + JSON.stringify(resources, null, 2),
  'export const AGENT_SKILL_PROMPTS = ' + JSON.stringify(prompts, null, 2),
  '',
].join('\n')

writeFileSync(outFile, content, 'utf8')
console.log(`Generated ${outFile} (${resources.length} resources, ${prompts.length} prompts)`)
